"""Describe actual old-wall clearance gains followed by another guard entry."""

import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parent


def main():
    step_path = OUT / 'normal_step_cluster_audit.csv'
    tangent_path = OUT.parent / 'high_don_mechanism_20261109/terminal_step_tangent_audit.csv'
    steps = pd.read_csv(step_path)
    tangents = pd.read_csv(tangent_path)
    # Full normal-step scan establishes that every observed guard crossing is
    # included below; do not silently select only terminal events beforehand.
    unsafe = steps.d_fresh_cluster_next_mm < steps.d_col_mm
    assert np.array_equal(unsafe.to_numpy(), steps.terminal_guard_entry.to_numpy())
    merged = steps[unsafe].merge(tangents[['source', 'seed', 'phi_before_mm']],
                                on=['source', 'seed'], validate='one_to_one')
    merged['old_distance_change_mm'] = merged.d_old_cluster_next_mm - merged.phi_before_mm
    merged['actual_guard_margin_mm'] = merged.d_fresh_cluster_next_mm - merged.d_col_mm
    merged['tradeoff_guard_entry'] = ((merged.old_distance_change_mm > 0)
                                     & (merged.d_old_cluster_next_mm >= merged.d_col_mm)
                                     & (merged.actual_guard_margin_mm < 0))
    merged.to_csv(OUT / 'terminal_distance_reversal.csv', index=False)
    groups = []
    for method in ('cc_sf', 'cc_mf'):
        all_steps = steps[steps.source == method]
        group = merged[merged.source == method]
        event = group[group.tradeoff_guard_entry]
        assert all_steps.seed.nunique() == 50
        assert event.seed.nunique() == len(event)
        groups.append(dict(source=method, attempted_trials=50, normal_steps=len(all_steps),
            all_guard_entry_trials=len(group), tradeoff_guard_entry_trials=len(event),
            trial_fraction=len(event) / 50, event_seeds=event.seed.tolist(),
            positive_change_tolerance_1e_minus6_mm_count=int((group.old_distance_change_mm > 1e-6).sum()),
            geometric_omission_gap_median_mm=float(group.geometric_ignore_gap_mm.median()),
            old_distance_change_min_max_mm=[float(group.old_distance_change_mm.min()), float(group.old_distance_change_mm.max())]))
    report = dict(
        definition='At current actual pose select nearest obstacle j_k. Its fresh signed distance increases over the recorded step and remains >=d_col, while the fresh global signed distance at the actual next pose is <d_col. All steps are generated by successful solver calls.',
        formula='d_jk(x_next)-d_jk(x_current)>0 AND d_jk(x_next)>=d_col AND min_j d_j(x_next)<d_col',
        scope='DoN .85; all 50 trials per controller, all eligible normal steps, including successful-trial prefixes and failed-trial endpoints. No covariance, probability model, probes, interpolated poses or solver execution.',
        limitation='Observed motion relative to current nearest obstacle; not recovery of the obstacle selected at an unlogged future-stage nominal state. An exploratory trajectory mechanism diagnostic, not proof of controller causation.',
        groups=groups,
        input_hashes={p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (step_path, tangent_path)},
        script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
    (OUT / 'clearance_tradeoff_summary.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 11,
                         'axes.spines.top': False, 'axes.spines.right': False})
    fig, axes = plt.subplots(1, 2, figsize=(12.8, 6.1), gridspec_kw={'width_ratios': [1.3, 1]})
    fig.subplots_adjust(left=.09, right=.97, bottom=.28, top=.78, wspace=.33)
    fig.suptitle('Moving away from one obstacle while entering another obstacle\'s guard', fontsize=16, y=.96)
    fig.text(.5, .89, 'DoN 0.85 | actual recorded geometry | all 50 trials per controller', ha='center', color='#555555')
    colors = {'cc_sf': '#bd5427', 'cc_mf': '#26739e'}
    ax = axes[0]
    for method, marker in [('cc_sf', 'o'), ('cc_mf', '^')]:
        g = merged[merged.source == method]
        ax.scatter(g.old_distance_change_mm, g.actual_guard_margin_mm,
                   c=colors[method], marker=marker, s=46, alpha=.85,
                   label=f'{method.upper().replace("_", "-")}: {len(g)} guard entries')
    ax.axvline(0, color='#333333', lw=1)
    ax.axhline(0, color='#333333', lw=1)
    ax.set(xlabel='Increase in previous-obstacle clearance (mm)',
           ylabel='Actual next clearance minus d_col (mm)',
           xlim=(-.60, 2.75), ylim=(-2.12, .20), title='(a) Recorded steps into a guard stop')
    ax.grid(alpha=.18)
    ax.legend(loc='lower left', frameon=False, fontsize=10)
    ax.text(.97, .94, 'Right of zero: moving away\nfrom the previous closest obstacle', transform=ax.transAxes, ha='right', fontsize=9, color='#555555')
    ax = axes[1]
    values = [r['tradeoff_guard_entry_trials'] for r in groups]
    bars = ax.bar([0, 1], values, color=[colors['cc_sf'], colors['cc_mf']], width=.52)
    for bar, count in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, count + .7, f'{count}/50 trials\n({count*2}%)', ha='center', fontsize=12)
    ax.set(xticks=[0, 1], xticklabels=['CC-SF', 'CC-MF'], ylabel='Trials with the specified event',
           ylim=(0, 22), title='(b) Trials with this executed-motion pattern')
    ax.grid(axis='y', alpha=.18)
    ax.set_axisbelow(True)
    fig.text(.09, .18, 'Event: previous-obstacle clearance increases and stays above 0.05 mm, while the actual global clearance falls below 0.05 mm.', fontsize=10)
    fig.text(.09, .13, 'The full normal-step scan contains 17,745 SF steps and 25,907 MF steps. Every observed guard entry is terminal in these runs.', fontsize=10)
    fig.text(.09, .08, 'This measures executed motion relative to the current nearest obstacle; it does not reconstruct the optimizer\'s future-stage feature choice.', fontsize=10)
    for ext in ('png', 'pdf', 'svg'):
        fig.savefig(OUT / f'executed_clearance_tradeoff.{ext}', dpi=220, facecolor='white')
    plt.close(fig)
    print(json.dumps(groups, indent=2))


if __name__ == '__main__':
    main()
